const clean = (s: string) =>
  s
    .toLowerCase()
    .replace(/\b(greater|metropolitan|metro|area|city of)\b/g, ' ')
    .replace(/[^\p{L}\s.,-]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/** The IANA zone for a location as LinkedIn or an email signature writes it, or undefined. */
export function zoneFromLocation(location: string | undefined): string | undefined {
  if (!location?.trim()) return undefined;
  const raw = location.toLowerCase();
  if (/\bbay area\b/.test(raw)) return 'America/Los_Angeles';
  const parts = clean(location)
    .split(',')
    .map((p) => p.trim())
    .filter(Boolean);
  // the city first ("Ann Arbor, Michigan"), then the state or province, then the country
  for (const p of parts) {
    const hit = CITIES[p] ?? CITIES[p.replace(/\./g, '')];
    if (hit) return hit;
  }
  for (const p of parts.slice(1).concat(parts.length === 1 ? parts : [])) {
    const s = STATES[p] ?? STATES[p.replace(/\./g, '')];
    if (s) return s;
  }
  for (const p of parts) {
    const c = COUNTRIES[p];
    if (c) return c;
  }
  // a city written alone with other words ("New York City Metropolitan")
  for (const [name, zone] of Object.entries(CITIES))
    if (name.length > 4 && clean(location).startsWith(name)) return zone;
  return undefined;
}

