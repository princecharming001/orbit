import { readFileSync, writeFileSync } from 'node:fs';
import { orgKey } from '../../packages/core/src/search/companies.ts';
const [S, out] = process.argv.slice(2);
const top = readFileSync(`${S}/data/words/count_1w.txt`, 'utf8').split('\n').slice(0, 30000).map((l) => l.split('\t')[0]).filter((w) => /^[a-z]+$/.test(w));
const yc = JSON.parse(readFileSync(`${S}/data/yc/all.json`, 'utf8')) as { name: string }[];
const ycWords = new Set<string>();
for (const c of yc) for (const w of orgKey(c.name).split(' ')) if (w) ycWords.add(w);
const keep = top.filter((w, i) => i < 8000 || ycWords.has(w));
const lines: string[] = [];
let line = '';
for (const w of keep) {
  if (line.length + w.length > 110) { lines.push(line.trim()); line = ''; }
  line += `${w} `;
}
if (line.trim()) lines.push(line.trim());
writeFileSync(out, `/**
 * Everyday English words and given names (plan 32 §18.4): a company whose whole name is one of these, or two of them,
 * is "ambiguous", so a bare name match in a headline counts only as a weak sign. Generated by
 * scripts/search/common_gen.ts from Peter Norvig's count_1w.txt (MIT): the 8,000 most frequent words, plus every word
 * of the 30,000 most frequent that appears in a YC company's name.
 */
const WORDS = \`
${lines.join('\n')}
\`;

export const COMMON_WORDS: ReadonlySet<string> = new Set(WORDS.split(/\\s+/).filter(Boolean));
`);
console.log(keep.length);
