#!/usr/bin/env node
/**
 * Bundles each account-mode Edge Function (§12.7) so it can import @orbit/core like the browser does.
 *
 * For every supabase/functions/<name>/main.ts:
 *   - esbuild bundles main.ts with its relative imports (../_shared/*) and @orbit/core, resolved to
 *     packages/core/src (`@orbit/core` → src/index.ts, `@orbit/core/<path>` → src/<path>.ts);
 *   - npm packages stay external and are rewritten to `npm:` specifiers with the exact versions in that function's
 *     deno.json import map (whose versions must equal the root package.json devDependencies the tests run on);
 *   - the bundle is written to supabase/functions/<name>/dist/index.js, and index.ts (the deployed entry) is the
 *     two-line file that imports it.
 *
 *   node scripts/build-functions.mjs           build
 *   node scripts/build-functions.mjs --check   fail when a committed bundle is stale (CI also runs git diff)
 *
 * orbit-claude and orbit-connectors have no main.ts and are deployed from source, unchanged.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fnDir = path.join(root, 'supabase/functions');
const coreSrc = path.join(root, 'packages/core/src');
const check = process.argv.includes('--check');

const INDEX = `// Deployed entry. Generated by scripts/build-functions.mjs from main.ts; run \`pnpm build:functions\` after a change.
import './dist/index.js';
`;
const BANNER = '// Generated by scripts/build-functions.mjs from main.ts. Do not edit; run `pnpm build:functions`.';

const rootPkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const pinned = { ...rootPkg.dependencies, ...rootPkg.devDependencies };

/** `npm:name@version[/sub]` from the import map, for a bare specifier such as `zod/v4` or `jose`. */
function npmSpecifier(spec, imports, fn) {
  if (imports[spec]) return imports[spec];
  const prefix = Object.keys(imports)
    .filter((k) => k.endsWith('/') && spec.startsWith(k))
    .sort((a, b) => b.length - a.length)[0];
  if (prefix) return imports[prefix] + spec.slice(prefix.length);
  throw new Error(`${fn}: "${spec}" is not in ${fn}/deno.json imports`);
}

function checkVersions(imports, fn) {
  for (const [key, target] of Object.entries(imports)) {
    const m = /^npm:((?:@[^/]+\/)?[^@/]+)@([^/]+)/.exec(target);
    if (!m) continue;
    const [, name, version] = m;
    if (pinned[name] !== version)
      throw new Error(`${fn}/deno.json pins ${name}@${version} (${key}) but package.json has ${pinned[name] ?? 'nothing'}`);
  }
}

function plugin(imports, fn) {
  return {
    name: 'orbit-functions',
    setup(b) {
      b.onResolve({ filter: /^@orbit\/core(\/.*)?$/ }, (a) => {
        const sub = a.path.slice('@orbit/core'.length).replace(/^\//, '');
        const file = sub ? path.join(coreSrc, `${sub}.ts`) : path.join(coreSrc, 'index.ts');
        if (!existsSync(file)) return { errors: [{ text: `${a.path} → ${file} does not exist` }] };
        return { path: file };
      });
      b.onResolve({ filter: /^(npm|jsr|node|https?):/ }, (a) => ({ path: a.path, external: true }));
      b.onResolve({ filter: /^[^./]/ }, (a) => {
        if (path.isAbsolute(a.path)) return undefined;
        try {
          return { path: npmSpecifier(a.path, imports, fn), external: true };
        } catch (e) {
          return { errors: [{ text: e.message }] };
        }
      });
    },
  };
}

const functions = readdirSync(fnDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(fnDir, d.name, 'main.ts')))
  .map((d) => d.name)
  .sort();

let stale = 0;
for (const fn of functions) {
  const dir = path.join(fnDir, fn);
  const imports = JSON.parse(readFileSync(path.join(dir, 'deno.json'), 'utf8')).imports ?? {};
  checkVersions(imports, fn);
  const result = await build({
    entryPoints: [path.join(dir, 'main.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'error',
    absWorkingDir: root,
    plugins: [plugin(imports, fn)],
  });
  const outputs = [
    [path.join(dir, 'dist/index.js'), result.outputFiles[0].text],
    [path.join(dir, 'index.ts'), INDEX],
  ];
  for (const [file, text] of outputs) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
    if (current === text) continue;
    if (check) {
      console.error(`stale: ${path.relative(root, file)}`);
      stale++;
      continue;
    }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${path.relative(root, file)} (${text.length} bytes)`);
  }
}
if (stale) {
  console.error(`${stale} generated file(s) are stale; run pnpm build:functions and commit the result.`);
  process.exit(1);
}
console.log(`${check ? 'checked' : 'built'} ${functions.join(', ')}`);
