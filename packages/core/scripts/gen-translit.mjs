// Generates src/entity/translit.data.ts from any-ascii (ISC, Hunter WB; see src/entity/anyascii.NOTICE), the
// table behind `transliterate` (src/entity/translit.ts). Core runs in the browser and in Deno functions and never
// reads files at run time, so the part of the table that names need is compiled into a module:
//   - the small blocks as any-ascii stores them (256 tab-separated renderings per block of 256 code points):
//     Latin, IPA, Greek, Cyrillic, Armenian, Hebrew, Arabic, the Indic scripts, Thai, Georgian, Ethiopic, Latin and
//     Greek extended (U+0000–U+1FFF), punctuation (U+2000–U+20FF), kana and bopomofo (U+3000–U+31FF), full-width
//     forms (U+FF00–U+FFFF);
//   - CJK ideographs (U+4E00–U+9FFF) as their 427 distinct readings plus two index characters per ideograph (half the
//     size of the raw table);
//   - Hangul syllables (U+AC00–U+D7A3) as the romanizations of their initial, vowel and final letters: any-ascii's
//     syllables are exactly those three joined, which this script checks for all 11,172 of them.
// Other blocks (emoji, rare ideographs) are left out: they render as nothing, and a name made only of them never
// matches anything. src/__tests__/translit.test.ts checks the module against any-ascii itself.
// Run: node packages/core/scripts/gen-translit.mjs   (any-ascii is a dev dependency of @orbit/core)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import anyAscii from 'any-ascii';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const out = join(root, 'packages', 'core', 'src', 'entity', 'translit.data.ts');
const ALPHABET = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
const at = (cp) => anyAscii(String.fromCodePoint(cp));

// 1. small blocks, in any-ascii's own layout (ASCII itself is passed through and stored empty)
const blockNums = [...Array.from({ length: 0x21 }, (_, i) => i), 0x30, 0x31, 0xff];
const blocks = blockNums.map((b) => {
  const cells = [];
  for (let lo = 0; lo < 256; lo++) {
    const cp = (b << 8) | lo;
    cells.push(cp <= 0x7f ? '' : at(cp));
  }
  // trailing empty cells are dropped, like any-ascii's own table
  while (cells.length && cells[cells.length - 1] === '') cells.pop();
  return [b, cells.join('\t')];
});

// 2. CJK ideographs: readings + a two-character index per ideograph
const readings = [];
const indexOf = new Map();
let index = '';
for (let cp = 0x4e00; cp <= 0x9fff; cp++) {
  const r = at(cp);
  if (!/^[A-Za-z]*$/.test(r))
    throw new Error(`unexpected reading ${JSON.stringify(r)} for U+${cp.toString(16)}`);
  if (!indexOf.has(r)) {
    indexOf.set(r, readings.length);
    readings.push(r);
  }
  const i = indexOf.get(r);
  if (i >= ALPHABET.length ** 2) throw new Error('too many readings for a two-character index');
  index += ALPHABET[Math.floor(i / ALPHABET.length)] + ALPHABET[i % ALPHABET.length];
}

// 3. Hangul: three letter tables, checked against every syllable
const syl = (l, v, t) => at(0xac00 + (l * 21 + v) * 28 + t).toLowerCase();
const initials = Array.from({ length: 19 }, (_, l) => syl(l, 0, 0).slice(0, -1)); // vowel 0 is "a"
const vowels = Array.from({ length: 21 }, (_, v) => syl(11, v, 0)); // initial 11 (ㅇ) is silent
const finals = Array.from({ length: 28 }, (_, t) => syl(11, 0, t).slice(1));
for (let l = 0; l < 19; l++)
  for (let v = 0; v < 21; v++)
    for (let t = 0; t < 28; t++)
      if (syl(l, v, t) !== initials[l] + vowels[v] + finals[t])
        throw new Error(`Hangul syllable ${l},${v},${t} is not its letters joined`);

const lit = (s) => JSON.stringify(s);
const text = `// Generated by packages/core/scripts/gen-translit.mjs from any-ascii 0.3.3 (ISC, Hunter WB; see anyascii.NOTICE).
// Do not edit by hand.

/** Blocks of 256 code points (code point >> 8) → their ASCII renderings, tab-separated, as any-ascii stores them. */
export const TRANSLIT_BLOCKS: Readonly<Record<number, string>> = {
${blocks.map(([b, s]) => `  ${b}: ${lit(s)},`).join('\n')}
};

/** The distinct readings of the CJK ideographs U+4E00–U+9FFF, separated by "|". */
export const CJK_READINGS = ${lit(readings.join('|'))};

/** Two characters of ${lit(ALPHABET)} per ideograph from U+4E00: the index of its reading. */
export const CJK_INDEX = ${lit(index)};

export const CJK_INDEX_ALPHABET = ${lit(ALPHABET)};

/** Hangul syllables: the romanization of the initial, vowel and final letters, joined. */
export const HANGUL_INITIALS: readonly string[] = ${lit(initials)};
export const HANGUL_VOWELS: readonly string[] = ${lit(vowels)};
export const HANGUL_FINALS: readonly string[] = ${lit(finals)};
`;
writeFileSync(out, text);
// in the repository's own style, so `biome check` passes on the generated file
execFileSync('npx', ['biome', 'format', '--write', out], { cwd: root, stdio: 'ignore' });
console.log(`wrote ${out} (${text.length} bytes, ${blocks.length} blocks, ${readings.length} CJK readings)`);
