// Generates src/entity/nicknames.data.ts from the vendored src/entity/nicknames.csv (carltonnorthern/nicknames,
// Apache-2.0). Core runs in the browser and in Deno functions and never reads files at run time, so the CSV is
// compiled into a module: one "name:nick nick nick" string per canonical name, sorted, lower-case.
// Run: node packages/core/scripts/gen-nicknames.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'entity');
const csv = readFileSync(join(dir, 'nicknames.csv'), 'utf8');
const groups = new Map();
for (const line of csv.split(/\r?\n/).slice(1)) {
  const [name, rel, nick] = line.split(',').map((s) => (s ?? '').trim().toLowerCase());
  if (!name || !nick || rel !== 'has_nickname' || name === nick) continue;
  if (!/^[a-z][a-z' -]*$/.test(name) || !/^[a-z][a-z' -]*$/.test(nick)) continue;
  const set = groups.get(name) ?? new Set();
  set.add(nick);
  groups.set(name, set);
}
const rows = [...groups.keys()]
  .sort()
  .map((k) => `  '${k.replace(/'/g, "\\'")}:${[...groups.get(k)].sort().join(' ').replace(/'/g, "\\'")}',`);
const out = `// Generated by packages/core/scripts/gen-nicknames.mjs from nicknames.csv (carltonnorthern/nicknames, Apache-2.0;
// see nicknames.NOTICE). Do not edit by hand.
// One entry per canonical given name: "name:nickname nickname ...".
export const NICKNAME_DATA: readonly string[] = [
${rows.join('\n')}
];
`;
writeFileSync(join(dir, 'nicknames.data.ts'), out);
console.log(`wrote ${groups.size} names`);
