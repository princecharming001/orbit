// Generates src/entity/zones.data.ts: which country each time zone is in, from the tz database's zone.tab (public
// domain), so a student's time zone gives the country their phone numbers are written for ("(555) 123-4567" in
// America/Chicago is +1 555 123 4567; "020 7946 0958" in Europe/London is +44 20 7946 0958).
// Run: node packages/core/scripts/gen-zones.mjs [path/to/zone.tab]   (default /usr/share/zoneinfo/zone.tab)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const out = join(root, 'packages', 'core', 'src', 'entity', 'zones.data.ts');
const src = readFileSync(process.argv[2] ?? '/usr/share/zoneinfo/zone.tab', 'utf8');
// older names browsers still report (the tz "backward" links), which zone.tab no longer lists
const BACKWARD = {
  'Asia/Calcutta': 'IN',
  'Asia/Saigon': 'VN',
  'Asia/Katmandu': 'NP',
  'Asia/Rangoon': 'MM',
  'Asia/Dacca': 'BD',
  'Asia/Thimbu': 'BT',
  'Asia/Ulan_Bator': 'MN',
  'Asia/Macao': 'MO',
  'Asia/Chongqing': 'CN',
  'Asia/Harbin': 'CN',
  'Asia/Istanbul': 'TR',
  'Asia/Tel_Aviv': 'IL',
  'Europe/Kiev': 'UA',
  'Europe/Belfast': 'GB',
  'America/Buenos_Aires': 'AR',
  'America/Indianapolis': 'US',
  'America/Louisville': 'US',
  'America/Fort_Wayne': 'US',
  'America/Montreal': 'CA',
  'Atlantic/Faeroe': 'FO',
  'Pacific/Truk': 'FM',
  'US/Eastern': 'US',
  'US/Central': 'US',
  'US/Mountain': 'US',
  'US/Pacific': 'US',
  'US/Alaska': 'US',
  'US/Hawaii': 'US',
  'US/Arizona': 'US',
  'Canada/Eastern': 'CA',
  'Canada/Central': 'CA',
  'Canada/Mountain': 'CA',
  'Canada/Pacific': 'CA',
  'Canada/Atlantic': 'CA',
  'Australia/ACT': 'AU',
  'Australia/NSW': 'AU',
  'Australia/Victoria': 'AU',
  'Australia/Queensland': 'AU',
  'Australia/West': 'AU',
  'Europe/London': 'GB',
};
const byCountry = new Map();
const add = (zone, cc) => byCountry.set(cc, [...new Set([...(byCountry.get(cc) ?? []), zone])]);
for (const line of src.split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , zone] = line.split('\t');
  if (cc && zone) add(zone, cc);
}
for (const [zone, cc] of Object.entries(BACKWARD)) add(zone, cc);
const rows = [...byCountry.keys()].sort().map((cc) => `${cc}:${byCountry.get(cc).sort().join(' ')}`);
const text = `// Generated by packages/core/scripts/gen-zones.mjs from the tz database's zone.tab (public domain). Do not edit.
/** "CC:Zone/One Zone/Two" per country (ISO 3166 code), for the country a time zone is in. */
export const ZONE_COUNTRIES: readonly string[] = ${JSON.stringify(rows)};
`;
writeFileSync(out, text);
execFileSync('npx', ['biome', 'format', '--write', out], { cwd: root, stdio: 'ignore' });
console.log(`wrote ${out} (${rows.length} countries)`);
