import { describe, expect, it } from 'vitest';
import {
  fitHopModel,
  hopFeatures,
  type IntroOutcome,
  MIN_OUTCOMES,
  type PathSnapshot,
  predictIntro,
} from '../graph/hopFit';

/** mulberry32 */
function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const snap = (ask: number, know: number, kind = 'linkedin_mutual'): PathSnapshot => ({
  score: ask * know,
  hops: [
    { fromId: 'user', toId: 'a', p: ask, kind: 'strength' },
    { fromId: 'a', toId: 't', p: know, kind },
  ],
});

describe('learning from intro outcomes (plan 21 §8)', () => {
  it('reads features from a route as it was weighed', () => {
    expect(hopFeatures(snap(0.6, 0.3))).toEqual([0.6, 0.3, 0.3, 2, 0, 0, 1, 0]);
    expect(hopFeatures(snap(0.6, 0.6, 'linkedin_engagement'))).toEqual([0.6, 0.6, 0.6, 2, 1, 0, 0, 0]);
  });

  it('refuses to fit before there are enough outcomes, or when they are all the same', () => {
    const few = Array.from({ length: MIN_OUTCOMES - 1 }, (_, i) => ({
      snapshot: snap(0.5, 0.3),
      outcome: (i % 2 ? 'agreed' : 'no_response') as IntroOutcome,
    }));
    expect(fitHopModel(few)).toBeUndefined();
    const same = Array.from({ length: MIN_OUTCOMES }, () => ({
      snapshot: snap(0.5, 0.3),
      outcome: 'agreed' as const,
    }));
    expect(fitHopModel(same)).toBeUndefined();
  });

  it('recovers that both halves of a route matter, from outcomes generated by them', () => {
    const r = rng(7);
    const examples = Array.from({ length: 600 }, () => {
      const ask = 0.2 + r() * 0.7;
      const know = 0.1 + r() * 0.8;
      return {
        snapshot: snap(ask, know),
        outcome: (r() < ask * know ? 'intro_made' : 'no_response') as IntroOutcome,
      };
    });
    const m = fitHopModel(examples)!;
    expect(m.n).toBe(600);
    expect(m.weights[0]).toBeGreaterThan(0);
    // the weakest later hop and its mean are the same feature here: together they carry the "know" half
    expect(m.weights[1]! + m.weights[2]!).toBeGreaterThan(0);
    expect(predictIntro(m, snap(0.85, 0.85))).toBeGreaterThan(predictIntro(m, snap(0.85, 0.15)));
    expect(predictIntro(m, snap(0.85, 0.85))).toBeGreaterThan(predictIntro(m, snap(0.25, 0.85)));
  });
});
